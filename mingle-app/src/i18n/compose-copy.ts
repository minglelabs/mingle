/** Compose copy resolved to one of the 15 primary UI locales. */
export function composeCopy(locale: string): ComposeCopy {
  return copy[resolveLegalDocumentLocale(resolveSupportedLocaleTag(locale) || 'en')]
}

/** Fill a `{token}` template, e.g. charCount / trashDaysLeft / bannerRateLimited. */
export function formatComposeCopy(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key) =>
    key in values ? String(values[key]) : match,
  )
}
