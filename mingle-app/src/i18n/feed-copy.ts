/** Feed UI copy for the given locale, resolved to one of the 15 primary UI locales. */
export function feedCopy(locale: string): FeedCopy {
  return copy[resolveLegalDocumentLocale(resolveSupportedLocaleTag(locale) || 'en')]
}

/** Substitute `{seconds}` into the rate-limit message. */
export function formatRateLimited(copyForLocale: FeedCopy, seconds: number): string {
  return copyForLocale.rateLimited.replace('{seconds}', String(Math.max(1, Math.ceil(seconds))))
}
