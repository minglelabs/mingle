/**
 * UI copy for the feed screen (W3 / C1), kept out of the shared dictionary so
 * eight teams can edit their own strings without colliding. Mirrors the
 * `profile-bio-copy.ts` pattern: one record per primary UI locale (15 total),
 * resolved through `resolveLegalDocumentLocale`.
 *
 * Long translations (German, Russian, etc.) must not overflow the compact
 * feed chrome — labels are kept short and the layout truncates rather than
 * wraps where space is tight.
 */
export type FeedCopy = {
  // Header
  compose: string
  notifications: string
  // Card actions
  like: string
  unlike: string
  comment: string
  more: string
  follow: string
  followed: string
  expand: string
  collapse: string
  translateShow: string
  translateHide: string
  translating: string
  translateFailed: string
  openImage: string
  closeImage: string
  // Accessibility navigation
  nextPost: string
  previousPost: string
  // First-run swipe hint ("swipe up for the next post") and its close button
  swipeHint: string
  swipeHintClose: string
  // Bell accessible name while unread notifications exist
  notificationsUnread: string
  // Follow feedback
  followFailed: string
  // Like feedback
  likeFailed: string
  // Rate limit (429): {seconds} is substituted
  rateLimited: string
  // Loading / error
  loading: string
  loadingMore: string
  loadMoreFailed: string
  imageFailed: string
  retry: string
  feedLoadFailed: string
  // Empty
  emptyTitle: string
  emptyAction: string
  // Deep-linked / restored post gone
  postUnavailable: string
  // Author's own archived / trashed post opened full-screen (read-only)
  archivedPostLabel: string
  trashedPostLabel: string
}

