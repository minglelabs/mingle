export function resolveConversationImageCopy(uiLocale: string): ConversationImageCopy {
  const supportedLocale = resolveSupportedLocaleTag(uiLocale) ?? DEFAULT_LOCALE
  const resolvedLocale = resolveLegalDocumentLocale(supportedLocale)
  return CONVERSATION_IMAGE_COPY_BY_LOCALE[resolvedLocale] ?? CONVERSATION_IMAGE_COPY_BY_LOCALE.en
}
