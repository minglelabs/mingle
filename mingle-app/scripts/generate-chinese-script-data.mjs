#!/usr/bin/env node
// Regenerates src/lib/chinese-script-data.ts from the OpenCC dictionaries
// shipped in opencc-js.
//
//   node scripts/generate-chinese-script-data.mjs
//
// A character is "Simplified-only" when OpenCC converts it to something else
// and it never appears in Traditional text (no Traditional phrase or variant
// dictionary produces it). "Traditional-only" is the mirror image. Both sets
// are limited to everyday characters (GB2312 level 1 / Big5 common) so the
// client bundle stays small; detection only needs frequent characters.
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import STCharacters from 'opencc-js/dict/STCharacters'
import STPhrases from 'opencc-js/dict/STPhrases'
import STPhrasesRegional from 'opencc-js/dict/STPhrases_GeneratedFromRegionalPhrases'
import TSCharacters from 'opencc-js/dict/TSCharacters'
import TSPhrases from 'opencc-js/dict/TSPhrases'
import TWPhrases from 'opencc-js/dict/TWPhrases'
import TWVariants from 'opencc-js/dict/TWVariants'
import TWVariantsPhrases from 'opencc-js/dict/TWVariantsPhrases'

const outputPath = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../src/lib/chinese-script-data.ts',
)

function parseDictionary(raw) {
  return raw.split('|').map((entry) => entry.split(' ')).filter((parts) => parts.length >= 2)
}

function charactersInValues(...dictionaries) {
  const output = new Set()
  for (const dictionary of dictionaries) {
    for (const [, ...values] of parseDictionary(dictionary)) {
      for (const value of values) for (const character of value) output.add(character)
    }
  }
  return output
}

function keysOf(dictionary) {
  return new Set(parseDictionary(dictionary).map(([key]) => key))
}

function decodeRange(encoding, firstBytes, secondBytes) {
  const decoder = new TextDecoder(encoding, { fatal: true })
  const output = new Set()
  for (const first of firstBytes) {
    for (const second of secondBytes) {
      try {
        const character = decoder.decode(new Uint8Array([first, second]))
        if (character.length === 1) output.add(character)
      } catch {
        // Unassigned code point in this range.
      }
    }
  }
  return output
}

function range(start, end) {
  return Array.from({ length: end - start + 1 }, (_, index) => start + index)
}

// GB2312 level 1 (3755 most common Simplified characters): rows 0xB0-0xD7.
const commonSimplified = decodeRange('gb18030', range(0xB0, 0xD7), range(0xA1, 0xFE))
// Big5 "frequently used" block (5401 characters): 0xA440-0xC67E.
const commonTraditional = new Set([
  ...decodeRange('big5', range(0xA4, 0xC5), [...range(0x40, 0x7E), ...range(0xA1, 0xFE)]),
  ...decodeRange('big5', [0xC6], range(0x40, 0x7E)),
])

const simplifiedToTraditional = new Map(parseDictionary(STCharacters).map(([key, ...values]) => [key, values]))
const traditionalToSimplified = new Map(parseDictionary(TSCharacters).map(([key, ...values]) => [key, values]))

const validInTraditional = charactersInValues(
  STCharacters, STPhrases, STPhrasesRegional, TWVariants, TWPhrases, TWVariantsPhrases,
)
for (const key of keysOf(TSCharacters)) validInTraditional.add(key)
const validInSimplified = charactersInValues(TSCharacters, TSPhrases)
for (const key of keysOf(STCharacters)) validInSimplified.add(key)

const isBmpHan = (character) => {
  const codePoint = character.codePointAt(0) ?? 0
  return character.length === 1 && codePoint >= 0x4E00 && codePoint <= 0x9FFF
}

const simplifiedOnly = [...simplifiedToTraditional.keys()]
  .filter((character) => isBmpHan(character)
    && !validInTraditional.has(character)
    && commonSimplified.has(character))
  .sort()
const traditionalOnly = [...traditionalToSimplified.keys()]
  .filter((character) => isBmpHan(character)
    && !validInSimplified.has(character)
    && commonTraditional.has(character))
  .sort()

const source = `// GENERATED by scripts/generate-chinese-script-data.mjs from opencc-js 1.4.2
// dictionaries. Do not edit by hand; rerun the script instead.
//
// Everyday characters that only occur in one Chinese script. Used to tell
// Simplified (zh-CN) text from Traditional (zh-TW) text without shipping the
// OpenCC dictionaries to the client.
export const SIMPLIFIED_ONLY_CHARACTERS =
  '${simplifiedOnly.join('')}'

export const TRADITIONAL_ONLY_CHARACTERS =
  '${traditionalOnly.join('')}'
`

writeFileSync(outputPath, source)
console.log(`wrote ${outputPath}: ${simplifiedOnly.length} simplified-only, ${traditionalOnly.length} traditional-only`)
